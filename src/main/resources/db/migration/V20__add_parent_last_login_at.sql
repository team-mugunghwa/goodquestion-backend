-- ============================================================
-- 마지막 접속 시각
-- V2에서 last_login_ip로 "어디서"는 남겼는데 "언제"가 빠져 있었다.
-- 로그인(이메일/소셜/가입)과 리프레시 토큰 재발급이 모두 이 컬럼을 갱신한다.
-- 재발급을 포함하는 이유는 액세스 토큰이 30분이라 며칠 만에 앱을 연 사용자가
-- 비밀번호 없이 재발급으로 들어오기 때문이다 - 그것도 접속이다.
-- last_login_ip와 같이 이력은 쌓지 않고 마지막 1건만 덮어쓴다.
-- 기존 행은 null로 남는다. 마지막 접속 시각을 모르는 것과 없는 것은 다르므로
-- 가입 시각 같은 값으로 채우지 않는다.
-- ============================================================

alter table parents
    add column last_login_at timestamptz;
