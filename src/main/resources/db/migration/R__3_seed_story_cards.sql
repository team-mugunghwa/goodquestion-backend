-- ============================================================
-- 이야기 목록 카드 시드 - Repeatable 마이그레이션
--
-- 프런트에는 표지 7종과 목록 화면이 이미 있는데 DB에는 이야기가 2편뿐이라,
-- 목록이 사실상 비어 보인다. 이 파일은 그 간극을 메우려고 **목록에 뜨는 데
-- 필요한 최소한**만 넣는다.
--
-- 담는 것   : topics 5종 추가 / stories 6편(카드 + 상세 화면용 child_role · intro)
--             / story_topics 연결
-- 안 담는 것: story_scenes, post_activity_config
--
-- 즉 **아직 플레이할 수 없는 이야기들이다.** 목록에는 뜨고 상세도 열리지만
-- sceneCount 가 0이라 세션 시작은 안 된다. 장면·대사가 준비되면 그때
-- R__1_seed_content.sql 로 옮기고 이 파일에서 해당 행을 지우는 것을 전제로 한다.
-- (`status` 를 DRAFT 로 두면 목록에서 아예 빠져 화면을 채우는 목적을 잃는다.
--  '표지만 있고 못 노는 이야기'를 노출할지는 콘텐츠팀 판단이 필요하다.)
--
-- R__1 이 아니라 별도 파일로 둔 이유: 콘텐츠팀이 R__1 을 계속 편집 중이라
-- 충돌을 만들지 않으려는 것이다. 합치는 편이 낫다면 그대로 옮겨도 된다.
-- Flyway 는 모든 V__ 이후 R__ 을 알파벳순으로 돌리므로 R__1 -> R__2 -> R__3 순서다.
--
-- 표지 출처: 프런트 저장소 assets/images/covers/story_*.png (2:3 세로).
-- 원본이 편당 2.5MB PNG 라 저장소와 이미지에 그대로 얹기엔 커서, 기존
-- banggui/cover.jpg 관례에 맞춰 폭 1024 JPEG(편당 약 300KB)로 변환해 넣었다.
-- ============================================================


